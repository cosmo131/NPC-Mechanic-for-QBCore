function Lang(key, vars)
    local locale = 'de'
    if Config and Config.Locale and Locales[Config.Locale] then
        locale = Config.Locale
    end

    local text = (Locales[locale] and Locales[locale][key]) or (Locales.de and Locales.de[key]) or key

    if vars then
        for varKey, value in pairs(vars) do
            text = text:gsub('{' .. varKey .. '}', tostring(value))
        end
    end

    return text
end
